# ISS-1 (bkz. CLAUDE.md KK-4): sirketler ayni finansal kalemi farkli US-GAAP
# etiketleriyle raporlar. Apple geliri "Revenues" ile DEGIL
# "RevenueFromContractWithCustomerExcludingAssessedTax" ile bildirir. Modelin
# dogru etiketi tahmin etmesini beklemek basarisiz arac cagrilari uretir.
# Cozum: anlamli takma adlar + aday etiketlerin sirali denenmesi.
CONCEPT_ALIASES: dict[str, list[str]] = {
    "revenue": [
        "RevenueFromContractWithCustomerExcludingAssessedTax",
        "Revenues",
        "SalesRevenueNet",
    ],
    "gross_profit": ["GrossProfit"],
    "operating_income": ["OperatingIncomeLoss"],
    "net_income": ["NetIncomeLoss"],
    "eps_diluted": ["EarningsPerShareDiluted"],
    "total_assets": ["Assets"],
    "total_liabilities": ["Liabilities"],
    "stockholders_equity": ["StockholdersEquity"],
    "cash": [
        "CashAndCashEquivalentsAtCarryingValue",
        "CashCashEquivalentsRestrictedCashAndRestrictedCashEquivalents",
    ],
    "operating_cash_flow": ["NetCashProvidedByUsedInOperatingActivities"],
    "rnd_expense": ["ResearchAndDevelopmentExpense"],
    "capex": ["PaymentsToAcquirePropertyPlantAndEquipment"],
}

ALIAS_LIST = ", ".join(sorted(CONCEPT_ALIASES))


def _gun_farki(start: str, end: str) -> int:
    a = date(*(int(x) for x in start.split("-")))
    b = date(*(int(x) for x in end.split("-")))
    return (b - a).days


def _yil(end: str) -> int:
    return int(end.split("-")[0])


def _fy_kaymasi(rows: list[dict]) -> tuple[int, bool]:
    """Sirketin mali yil ADLANDIRMA kaymasini SEC verisinden turetir.

    Neden heuristik degil (bkz. CLAUDE.md KK-7): "Ocak-Haziran'da biten donem
    onceki yila sayilir" kurali olculdu ve WMT/NKE/MSFT'de YANLIS cikti. Ters
    kural da guvenli degil - Target/Gap Subat'ta biten yili BASLADIGI yilla
    adlandirir. Yani evrensel bir kural yok.

    Turetme: SEC'in `fy` alani bir 10-K'nin KENDI donemi icin dogrudur (DEI
    DocumentFiscalYearFocus'tan gelir); yanlis olan sadece ayni dosyalamadaki
    karsilastirma yillaridir. Her `fy` grubunda en gec biten donem, o
    dosyalamanin kendi donemidir -> capa. kayma = fy - bitis_yili.

    Doner: (kayma, veriden_turetildi_mi). Capa yoksa (0, False).
    """
    capalar: dict[int, str] = {}
    for r in rows:
        if r.get("fp") != "FY" or not str(r.get("form", "")).startswith("10-K"):
            continue
        end, start, fy = r.get("end"), r.get("start"), r.get("fy")
        if not end or fy is None:
            continue
        if start and not (300 <= _gun_farki(start, end) <= 400):
            continue
        if fy not in capalar or end > capalar[fy]:
            capalar[fy] = end

    if not capalar:
        return 0, False

    kaymalar = [fy - _yil(end) for fy, end in capalar.items()]
    # En sik gorulen kayma; tek tuk transition period'lar sonucu bozmasin.
    # Esitlikte kucuk kayma kazanir - sonuc deterministik olsun.
    kayma = sorted(set(kaymalar), key=lambda k: (-kaymalar.count(k), k))[0]
    return kayma, True

_client: EdgarClient | None = None


def _c() -> EdgarClient:
    global _client
    if _client is None:
        _client = EdgarClient()
    return _client


# ----------------------------------------------------------------- semalar
class CompanyProfile(BaseModel):
    cik: str = Field(description="10-digit zero-padded SEC Central Index Key")
    name: str = Field(description="Official registrant name as filed with the SEC")
    ticker: str
    sic_description: str | None = Field(default=None, description="Standard Industrial Classification description")
    fiscal_year_end: str | None = Field(default=None, description="Fiscal year end as MMDD, e.g. 0927")


class Filing(BaseModel):
    form: str = Field(description="Filing type, e.g. 10-K, 10-Q, 8-K")
    filing_date: str = Field(description="Date the filing was submitted, ISO 8601")
    report_date: str | None = None
    accession_number: str
    primary_document_url: str


class FilingPage(BaseModel):
    ticker: str
    total_matching: int = Field(
        description="Total filings matching form_type in the recent-filings feed"
    )
    returned: int = Field(description="Number of filings in this response")
    has_more: bool = Field(
        description="True if more filings matched than were returned; raise limit "
        "or narrow with form_type"
    )
    filings: list[Filing]


class FactPoint(BaseModel):
    fiscal_year: int = Field(
        description="The company's own fiscal year label, derived from SEC data rather than guessed"
    )
    source_tag: str = Field(description="US-GAAP tag this value was reported under")
    period_start: str | None = Field(default=None, description="Period start date; empty for instant (point-in-time) facts")
    period_end: str = Field(description="Period end date - the only reliable identifier of a period")
    days: int | None = Field(default=None, description="Period length in days")
    value: float
    unit: str
    form: str = Field(description="Filing type the value was taken from")
    filed: str = Field(description="Date this value was filed with the SEC")


class ConceptSeries(BaseModel):
    cik: str
    requested_concept: str = Field(description="The alias or tag the caller supplied")
    resolved_concepts: list[str] = Field(
        description="US-GAAP tags that returned data and were MERGED into this series"
    )
    fiscal_year_derived: bool = Field(
        description="True: fiscal year labels were derived from the company's own SEC "
        "filings. False: no anchor filing was found, so the calendar year of the "
        "period end was used instead - treat these labels as less reliable."
    )
    taxonomy: str
    label: str | None = None
    source_endpoint: str = Field(
        default="companyconcept",
        description="Which SEC endpoint supplied these facts. Normally "
        "companyconcept. It reads companyfacts instead when companyconcept "
        "answered with no facts at all, which SEC does for some companies in "
        "some regions.",
    )
    total_periods: int = Field(
        description="Periods available after merging and de-duplication"
    )
    returned: int = Field(description="Periods in this response")
    has_more: bool = Field(
        description="True if older periods exist beyond this response; the most "
        "recent are returned first-to-last, so raise limit to reach further back"
    )
    points: list[FactPoint]


class ConceptInfo(BaseModel):
    tag: str = Field(description="US-GAAP tag; can be passed verbatim to sec_edgar_get_concept_series")
    label: str | None = Field(default=None, description="Human-readable label as published by the SEC")
    units: list[str] = Field(description="Units available for this tag, e.g. USD, shares")
    data_points: int = Field(description="Number of reported data points for this tag")


class ConceptCatalog(BaseModel):
    cik: str
    total_matching: int = Field(description="Total number of tags matching the filter")
    returned: int = Field(description="Number of tags returned in this response")
    has_more: bool = Field(description="True if more tags matched than were returned; narrow with search")
    concepts: list[ConceptInfo]


