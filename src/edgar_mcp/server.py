@mcp.tool(
    name="sec_edgar_compare_companies",
    annotations=ToolAnnotations(
        read_only_hint=True,
        destructive_hint=False,
        idempotent_hint=True,
        open_world_hint=True,
    ),
    description=(
        "Compares one financial concept across ALL companies that reported it "
        "for a single period, ranked by value. Use it for questions of the form "
        "'how does X compare with its peers' or 'who reported the most Y in "
        "period Z'. The other tools answer about one company at a time; this "
        "one answers about a population.\n"
        "Two things about SEC's period buckets that change how the answer "
        "should be read, both reported in the response rather than hidden: a "
        "company's own period end can differ from the calendar frame by weeks "
        "(measured in the CY2025Q1 revenue frame: ends from 2025-02-23 to "
        "2025-05-04, seventy days apart), and a "
        "company missing from a frame has NOT necessarily failed to report the "
        "concept."
    ),
)
async def compare_companies(
    concept: Annotated[
        str,
        Field(
            description=(
                "An alias (revenue, net_income, total_assets, ...) or a raw tag. "
                "A frame is read under ONE tag, so unlike "
                "sec_edgar_get_concept_series no tags are merged; the tag that "
                "answered is named in the response."
            )
        ),
    ],
    period: Annotated[
        str,
        Field(
            description="Calendar year (2025 / CY2025) or quarter (2025Q1 / "
            "CY2025Q1). Add I for a balance-sheet date (CY2025Q1I); if the "
            "wrong one is asked for, the counterpart is tried automatically."
        ),
    ],
    unit: Annotated[
        str,
        Field(default="USD", description="Unit of measure, e.g. USD or shares"),
    ] = "USD",
    tickers: Annotated[
        list[str] | None,
        Field(
            default=None,
            description="Restrict the answer to these companies while still "
            "ranking them against the whole frame. Any that the frame does not "
            "hold come back in missing_tickers instead of being dropped.",
        ),
    ] = None,
    order: Annotated[
        Literal["value_desc", "value_asc"],
        Field(default="value_desc", description="Sort direction by value"),
    ] = "value_desc",
    limit: Annotated[
        int,
        Field(default=25, ge=1, le=100,
              description="Maximum companies to return; check has_more"),
    ] = 25,
    ctx: Context | None = None,
) -> CompanyComparison:
    await _ilerleme(ctx, 0, 2, "Reading the frame from SEC")
    cerceve = _cerceve_normalle(period)
    anahtar = concept.strip().lower()
    adaylar = CONCEPT_ALIASES.get(anahtar, [concept.strip()])

    bulunan = None
    for aday in adaylar:
        taksonomi, etiket = _bol(aday)
        bulunan = await _cerceve_verisi(taksonomi, etiket, unit, cerceve)
        if bulunan is not None:
            secilen_taksonomi, secilen_etiket = taksonomi, etiket
            break

    if bulunan is None:
        raise ValueError(
            f"SEC has no frame for '{concept}' in {cerceve} with unit '{unit}' "
            f"(tried: {', '.join(adaylar)}, and the duration/instant "
            "counterpart of that frame). A frame exists only for periods SEC "
            "has assembled; try the annual frame (e.g. CY2025), a different "
            "unit, or sec_edgar_list_available_concepts to find the tag a "
            "company reports this under."
        )

    veri, kullanilan = bulunan
    satirlar = veri.get("data") or []
    await _ilerleme(ctx, 1, 2, f"Ranking {len(satirlar)} companies")
    if not satirlar:
        raise ValueError(
            f"The frame {kullanilan} for {secilen_etiket} exists but holds no "
            "companies. This is an upstream anomaly, not an empty answer to a "
            "valid question - reading it as 'nobody reported this' would be "
            "wrong."
        )

    ters = order == "value_desc"
    sirali = sorted(satirlar, key=lambda r: float(r.get("val") or 0), reverse=ters)

    # Bir CIK birden fazla sembol tasiyabilir (GOOG/GOOGL, FOX/FOXA, BRK-A/B).
    # CIK'i anahtar yapan ilk surumde ikinci sembol birinciyi eziyor ve istenen
    # sirket ne `companies`'te ne `missing_tickers`'ta goruluyordu - alanin
    # kendi vaadi "dusurulmez" derken (15 Agu 2026'da bulundu).
    istenen: dict[str, list[str]] = {}
    if tickers:
        for t in tickers:
            istenen.setdefault((await _kimlik_coz(t))[0], []).append(t.strip().upper())

    secilenler: list[CompanyValue] = []
    gorulen: set[str] = set()
    for i, r in enumerate(sirali, 1):
        cik = str(r.get("cik", "")).zfill(10)
        if istenen and cik not in istenen:
            continue
        gorulen.add(cik)
        if len(secilenler) >= limit:
            continue
        secilenler.append(
            CompanyValue(
                rank=i,
                cik=cik,
                ticker=(", ".join(istenen[cik]) if cik in istenen
                        else await _c().ticker_for_cik(cik)),
                company=str(r.get("entityName", "")).strip(),
                location=r.get("loc"),
                value=float(r.get("val") or 0),
                period_start=r.get("start"),
                period_end=str(r.get("end", "")),
                accession_number=str(r.get("accn", "")),
            )
        )

    # `total_companies` alanin kendi tanimi: "cercevenin kac sirket tasidigi".
    # Ticker filtresi uygulaninca bunu filtrelenmis sayiyla degistirmek, 2.543
    # sirketlik bir cerceve icin "total_companies: 1" demek olurdu - ve `rank`
    # tum cerceveye gore verildiginden model "1 sirketin 12.'si" gorurdu.
    eslesen_sayisi = len(sirali)
    gosterilen_sayisi = len(gorulen) if istenen else len(sirali)
    bitisler = sorted(str(r.get("end", "")) for r in satirlar if r.get("end"))
    return CompanyComparison(
        concept=concept,
        resolved_tag=secilen_etiket,
        tags_tried=adaylar,
        taxonomy=secilen_taksonomi,
        unit=unit,
        frame=kullanilan,
        frame_requested=cerceve,
        frame_kind="instant" if kullanilan.endswith("I") else "duration",
        total_companies=eslesen_sayisi,
        matching_request=gosterilen_sayisi,
        returned=len(secilenler),
        has_more=gosterilen_sayisi > len(secilenler),
        period_end_earliest=bitisler[0] if bitisler else "",
        period_end_latest=bitisler[-1] if bitisler else "",
        companies=secilenler,
        missing_tickers=sorted(
            ad for cik, adlar in istenen.items() if cik not in gorulen
            for ad in adlar
        ),
    )


# ------------------------------------------------------- boyutlu XBRL (C)
# SEC'in XBRL REST API'si boyutlu fact tasimaz; segment kirilimi yalnizca
# dosyalamanin XBRL instance'inda var. Ayristirma `belge.py`den ayri bir
# modulde (`xbrl.py`), cunku biri HTML biri XML - ayni yere koymak ikisini de
# bulanik hale getirirdi.
_INSTANCE: dict[str, Instance] = {}
INSTANCE_SINIRI = 2

# SEC'in inline belgeden ayikladigi instance: `tsla-20251231_htm.xml`.
_AYIKLANAN_INSTANCE = re.compile(r"_htm\.xml$", re.IGNORECASE)
# 2019-2021 oncesi dosyalamalarda inline XBRL yoktu; instance'i DOSYALAYAN
# sunardi (EX-101.INS, `tsla-20181231.xml`). Linkbase ve sema dosyalari ayni
# uzantiyi paylasir, onlar elenmeli.
_LINKBASE = re.compile(r"_(cal|def|lab|pre)\.xml$", re.IGNORECASE)


async def _instance_url(dizin: str, belgeler: list[FilingDocument]) -> str:
    """Dosyalamanin XBRL instance dosyasinin adresi.

    Once SEC'in ayikladigi `*_htm.xml`; yoksa (inline XBRL zorunluluğundan
    onceki dosyalamalar - buyuk hizlandirilmis dosyalayanlar icin 15 Haziran
    2019, digerleri icin 2020/2021 sonrasi biten donemler) dosyalayanin sundugu
    bagimsiz instance aranir. Hicbiri yoksa hata EYLEME DONUSTURULEBILIR olmali:
    hangi dosyalamanin XBRL tasimadigini soylemek, bos donmekten iyidir.
    """
    veri = await _c().filing_index(dizin)
    adlar = [str(x.get("name", "")) for x in (veri.get("directory") or {}).get("item", [])]

    for ad in adlar:
        if _AYIKLANAN_INSTANCE.search(ad):
            return f"{dizin}/{ad}"
    for ad in adlar:
        if ad.lower().endswith(".xml") and not _LINKBASE.search(ad) \
                and not ad.lower().startswith(("metalinks", "filingsummary")):
            return f"{dizin}/{ad}"
    raise ValueError(
        "This filing has no XBRL instance document, so it carries no tagged "
        "facts to break down. Filings before inline XBRL became mandatory "
        "(fiscal periods ending 2019-06-15 for large accelerated filers, later "
        "for smaller ones) may predate tagging entirely. Files present: "
        f"{', '.join(adlar[:20]) or 'none'}."
    )


async def _instance(dizin: str, belgeler: list[FilingDocument]) -> tuple[Instance, str]:
    url = await _instance_url(dizin, belgeler)
    if url not in _INSTANCE:
        cozulmus = ayristir(await _c().filing_document(url))
        if len(_INSTANCE) >= INSTANCE_SINIRI:
            _INSTANCE.pop(next(iter(_INSTANCE)))
        _INSTANCE[url] = cozulmus
    return _INSTANCE[url], url


# Etiket linkbase'i: QName'leri insan okunur adlara baglar. Ayri onbellek,
# instance ile ayni sinirla; olculdu (15 Agu 2026): TSLA FY2025'te instance
# 2,68 MB, etiket linkbase'i 1,21 MB. Yani etiketler cagrinin indirme
# hacmini yaklasik yarim kat artiriyor - bu yuzden kapatilabilir.
_ETIKET: dict[str, Etiketler] = {}
ETIKET_SINIRI = 2
_ETIKET_DOSYASI = re.compile(r"_lab\.xml$", re.IGNORECASE)
BOS_ETIKET = Etiketler()


async def _etiketler(dizin: str) -> tuple[Etiketler, str | None]:
    """Dosyalamanin etiket linkbase'i. Yoksa bos harita ve None.

    Etiketin kaynagi bilincli olarak DOSYALAMANIN KENDI dizini: adlar, o
    dosyalamanin ilan ettigi adlardir. Standart etiketler US-GAAP
    taksonomisinden, uzanti etiketleri sirketin kendi taksonomisinden gelir.
    SEC'in bu dosyayi - ayikladigi instance'ta oldugu gibi - yeniden uretip
    uretmedigi DOGRULANMADI; dogrulanan sey dosyanin dosyalamanin dizininde
    durdugu ve etiket metinlerinin oradan geldigi.
    """
    veri = await _c().filing_index(dizin)
    for x in (veri.get("directory") or {}).get("item", []):
        ad = str(x.get("name", ""))
        if not _ETIKET_DOSYASI.search(ad):
            continue
        url = f"{dizin}/{ad}"
        if url not in _ETIKET:
            cozulmus = etiketleri_ayristir(await _c().filing_document(url))
            if len(_ETIKET) >= ETIKET_SINIRI:
                _ETIKET.pop(next(iter(_ETIKET)))
            _ETIKET[url] = cozulmus
        return _ETIKET[url], ad
    return BOS_ETIKET, None


async def _dosyalama_ve_instance(
    ticker: str, accession: str | None, form_type: str,
    ctx: Context | None = None, etiket_iste: bool = False,
) -> tuple[dict, Instance, str, Etiketler, str | None]:
    adim_sayisi = 4 if etiket_iste else 3
    await _ilerleme(ctx, 0, adim_sayisi, "Locating the filing")
    cik, _ = await _kimlik_coz(ticker)
    kayit = await _dosyalama_bul(cik, accession, form_type)
    dizin = (
        f"{SEC_WWW}/Archives/edgar/data/{int(cik)}/"
        f"{kayit['accession_number'].replace('-', '')}"
    )
    belgeler = await _okunabilir_belgeler(dizin, kayit["primary_document"])
    await _ilerleme(ctx, 1, adim_sayisi, "Downloading the XBRL instance")
    inst, url = await _instance(dizin, belgeler)
    etiketler, etiket_dosyasi = BOS_ETIKET, None
    if etiket_iste:
        await _ilerleme(ctx, 2, adim_sayisi, "Downloading the label linkbase")
        etiketler, etiket_dosyasi = await _etiketler(dizin)
    await _ilerleme(ctx, adim_sayisi - 1, adim_sayisi, f"Read {len(inst.olgular)} facts")
    return kayit, inst, url, etiketler, etiket_dosyasi


